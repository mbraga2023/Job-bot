def normalize_technology(value: str) -> str | None:
    """
    Converts a technology variation into its canonical name.

    Example:

        playwright
        Playwright automation
        PLAYWRIGHT

    all become:

        PLAYWRIGHT
    """

    if not value:
        return None

    normalized = (
        value
        .strip()
        .lower()
    )

    for canonical, aliases in TECHNOLOGY_ALIASES.items():

        if normalized in aliases:
            return canonical

    return None
